// Generates src/deployment.ts from the hash-verified site manifest, and writes the agent-facing
// files the site serves (public/agent.json, public/skill.md). Never hand-edit the outputs.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toBytes } from "viem";

const here = dirname(fileURLToPath(import.meta.url));
const agent = resolve(here, "..");
const web = resolve(agent, "../web");
const pub = resolve(web, "public");

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([k, v]) => [k, canonical(v)]),
    );
  return value;
}
const hashAbi = (abi) => keccak256(toBytes(JSON.stringify(canonical(abi)))).slice(2);
const json = async (p) => JSON.parse(await readFile(p, "utf8"));

const deployment = await json(resolve(pub, "imd-deployment.json"));
const history = await json(resolve(pub, "history-start.json"));
const abis = {};
for (const c of deployment.contracts) {
  const abi = await json(resolve(pub, c.abiPath));
  const hash = hashAbi(abi);
  if (hash !== c.abiHash) throw new Error(`ABI hash mismatch for ${c.name}: ${hash} != ${c.abiHash}`);
  abis[c.name] = abi;
}
const weir = deployment.contracts.find((c) => c.name === "Weir");
const token = deployment.contracts.find((c) => c.name === "LaunchToken");
if (!weir || !token) throw new Error("manifest lacks Weir or LaunchToken");

// Rules of the deployed v2 contract that are not readable from the ABI alone.
const rules = {
  minHoldWeir: "10000",
  tiers: [
    { minWeir: "0", bondBps: 500 },
    { minWeir: "100000", bondBps: 250 },
    { minWeir: "1000000", bondBps: 100 },
    { minWeir: "10000000", bondBps: 0 },
  ],
  disputeTimeoutSeconds: 604800,
  disputerFeeShareBps: 2000,
  courtFundSubsidiesPerUtcDay: 5,
  maxTermsUriBytes: 512,
  maxNoteBytes: 280,
  panelSize: 5,
  quorum: 4,
  oraclePriceImdAtLaunch: "0.5",
  maxOraclePriceImd: "5",
};
const knownTokens = [
  { symbol: "USDG", address: "0x5fc5360d0400a0fd4f2af552add042d716f1d168", decimals: 6, note: "the chain's dollar" },
  { symbol: "WEIR", address: token.address, decimals: 18, note: "the hold-gate token" },
  { symbol: "IMD", address: deployment.network.pairToken.address, decimals: 18, note: "pays the oracle fee" },
  { symbol: "WETH", address: "0x0bd7d308f8e1639fab988df18a8011f41eacad73", decimals: 18, note: "ETH wrapped; unwrap with withdraw()" },
];
const links = {
  site: "https://weir.cool",
  repo: "https://github.com/identity-md-launches/launch-1869-weir-v2-deploy-weir",
  explorer: deployment.network.explorer,
  imdExplorer: "https://explorer.imd.fun",
  imdApi: "https://api.imd.fun",
  oracleDocs: "https://imd.fun/docs/#oracle-body",
};

const ts = `// GENERATED by scripts/sync.mjs from web/public/imd-deployment.json. Do not edit.
export const deployment = ${JSON.stringify(
  {
    version: deployment.version,
    launchId: deployment.launchId,
    chainId: deployment.chainId,
    sourceCommit: deployment.sourceCommit,
    attestationHash: deployment.attestationHash,
    deployedBlock: history.fromBlock,
    weir: weir.address,
    weirAbiHash: weir.abiHash,
    weirToken: token.address,
    imd: deployment.network.pairToken.address,
    network: deployment.network,
    poolKey: deployment.poolKey,
  },
  null,
  2,
)} as const;
export const rules = ${JSON.stringify(rules, null, 2)} as const;
export const knownTokens = ${JSON.stringify(knownTokens, null, 2)} as const;
export const links = ${JSON.stringify(links, null, 2)} as const;
export const weirAbi = ${JSON.stringify(abis.Weir)} as const;
`;
await mkdir(resolve(agent, "src"), { recursive: true });
await writeFile(resolve(agent, "src/deployment.ts"), ts);

// Machine-readable manifest for agents, served beside the site.
const agentJson = {
  name: "Weir",
  description:
    "Per-second ERC-20 streams from a client to a recipient under written terms, with a five-reviewer dispute court (IdentityMD oracle). No owner, no admin, no fee, no upgrade path. Not audited.",
  version: 1,
  chainId: deployment.chainId,
  network: {
    name: deployment.network.name,
    rpcUrls: deployment.network.rpcUrls,
    explorer: deployment.network.explorer,
    nativeCurrency: deployment.network.nativeCurrency,
  },
  contracts: {
    weir: { address: weir.address, abi: "abi/Weir.json", abiHash: weir.abiHash },
    weirToken: { address: token.address, abi: "abi/LaunchToken.json", abiHash: token.abiHash, symbol: "WEIR", decimals: 18 },
    imd: { address: deployment.network.pairToken.address, symbol: "IMD", decimals: 18 },
  },
  deployedBlock: history.fromBlock,
  rules,
  knownTokens,
  links,
  agent: {
    docs: "llms.txt",
    skill: "skill.md",
    sdk: { npm: "weir-agent", source: "https://github.com/weircool/weir/tree/main/agent" },
    mcp: { command: "npx", args: ["-y", "weir-agent", "weir-mcp"], env: ["WEIR_PRIVATE_KEY", "WEIR_RPC_URLS"] },
  },
};
await writeFile(resolve(pub, "agent.json"), JSON.stringify(agentJson, null, 2) + "\n");
await writeFile(resolve(pub, "skill.md"), await readFile(resolve(agent, "SKILL.md"), "utf8"));
console.log(`synced: Weir ${weir.address} on ${deployment.chainId}, deployed block ${history.fromBlock}`);
